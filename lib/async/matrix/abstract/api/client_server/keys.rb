          # v1.2 added fallback keys to the upload.
          module V1_2
            # @parameter fallback_keys [Hash | nil] the keys to fall back on when one time keys run out.
            # @returns [Hash] the fields.
            def upload_fields(fallback_keys: nil, **options)
              super(**options).tap do |fields|
                if fallback_keys
                  fields[:fallback_keys] = fallback_keys
                end
              end
            end
          end

