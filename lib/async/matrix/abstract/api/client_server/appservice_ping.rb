          # v1.7 added pinging an application service.
          module V1_7
            # Ask the homeserver to ping an application service, which only that service may do.
            #
            # @parameter appservice_id [String] the application service to ping.
            # @parameter transaction_id [String | nil] the transaction to quote in the ping.
            # @returns [Ping] how long the ping took.
            def ping_appservice(appservice_id, transaction_id: nil)
              payload = {transaction_id: transaction_id}.compact
              path = "#{V1}/appservice/#{::Protocol::URL::Encoding.escape(appservice_id)}/ping"

              api::Ping.post(@resource.with(path: path), payload)
            end
          end

