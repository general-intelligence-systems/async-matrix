          # v1.6 added the timestamp lookup.
          module V1_6
            # The event nearest a point in time.
            #
            # @parameter room_id [String] the room to search.
            # @parameter ts [Integer] the timestamp to search from, in milliseconds since the epoch.
            # @parameter dir [String] `f` to search forwards from it, `b` to search backwards.
            # @returns [EventByTimestamp] the event the homeserver found.
            def get_event_by_timestamp(room_id, ts, dir: "f")
              path = "#{V1}/rooms/#{::Protocol::URL::Encoding.escape(room_id)}/timestamp_to_event"

              api::EventByTimestamp.get(@resource.with(path: path, parameters: {ts: ts, dir: dir}))
            end
          end

