          module V1_1
            # @returns [Hash] what the server says it is running.
            def server
              self.value[:server] || {}
            end

            # @returns [String | nil] the name of the software, e.g. `Synapse`.
            def name
              self.server[:name]
            end

            # Deliberately not `version`, which is the specification version this class implements.
