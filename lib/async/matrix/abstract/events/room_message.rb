# The version layers for `room_message.rb`. Each module mirrors the class of the same name, and
# holds only what a given specification version changed: the unversioned implementation stays in
# the class.
#
# The field groups are named absolutely, because inside `Abstract::Events` the name `Events`
# resolves to that module rather than to the one holding the classes.
#
# The field groups these layers add live in `events/fields.rb` rather than beside the classes
# which use them: a layer is applied when a class is derived, so it must be loadable before the
# classes are, and anything it includes has to come from somewhere neither one requires.
#
# Only the types which actually changed have a container here. A type which never changed asks
# nothing of a reader, and `m.room.message-<version>.deltas.yaml` beside the schemas is what says
# so - the four media messages are the only ones which changed, and all of them in v1.10.

